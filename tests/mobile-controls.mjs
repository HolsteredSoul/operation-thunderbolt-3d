import assert from 'node:assert/strict';
import {chooseTouchTarget,TouchControls} from '../src/touch.js';
import {Controls} from '../src/input.js';
const p={x:0,y:0,angle:0},e=(x,y=0)=>({x,y,hp:100,dead:false}),near=e(100),behind=e(-80),far=e(501),dead={...e(30),dead:true},blocked=e(40);
const visible=t=>t!==blocked;
assert.equal(chooseTouchTarget(p,[near,behind,far,dead,blocked],null,visible),behind);
assert.equal(chooseTouchTarget(p,[near,behind],near,visible),near,'retain eligible target while dodging');
assert.equal(chooseTouchTarget(p,[far,dead,blocked],null,visible),null);
assert.equal(chooseTouchTarget(p,[near],behind,visible),near,'removed target is released');
const g={player:p,enemies:[near],state:'playing',keys:{},mouse:{down:false}};
const t=Object.assign(Object.create(TouchControls.prototype),{g,enabled:true,portrait:false,visible,move:{x:.5,y:.2},angle:0,target:near,held:true});
assert.equal(t.sample().fire,true);t.target=behind;assert.equal(t.sample().fire,false,'do not fire while turning away from target');
t.target=blocked;assert.equal(t.sample().fire,false,'cover excludes firing');t.target=far;assert.equal(t.sample().fire,false,'range excludes firing');
t.target=near;t.portrait=true;assert.equal(t.sample().fire,false);t.portrait=false;t.held=false;assert.equal(t.sample().fire,false);t.held=true;
const controls=new Controls(g,{});g.input=controls;controls.source='touch';controls.touch=t;
let resets=0;t.reset=()=>resets++;
controls.poll(1/60,[]);assert.equal(resets,0);assert.equal(controls.sample().moveX,.5);
controls.suspended=true;assert.equal(controls.sample().fire,false);assert.equal(controls.sample().moveX,0);controls.suspended=false;
controls.useMouse();assert.equal(resets,1);assert.equal(controls.source,'mouse');assert.equal(controls.sample().fire,false);
console.log('PASS touch targeting, stable selection, cover/range/death exclusions, deliberate firing, suspension and desktop handoff');
